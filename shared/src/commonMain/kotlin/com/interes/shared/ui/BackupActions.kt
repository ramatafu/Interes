package com.interes.shared.ui

import androidx.compose.runtime.Composable
import com.interes.shared.storage.BackupPaths

/**
 * В отличие от rememberImagePicker (который просто отдаёт путь/Uri
 * выбранного файла) эти два триггера выполняют ВСЮ операцию целиком —
 * и выбор места, и упаковку/распаковку ZIP. Причина: на Android системный
 * диалог "Сохранить как" (Storage Access Framework) отдаёт content:// Uri,
 * в который можно только писать через contentResolver, а не обычный путь
 * файла на диске — то есть на Android эти два шага (выбор места и запись
 * файла) физически разные API и не разделяются так же чисто, как на
 * Desktop (java.awt.FileDialog сразу даёт обычный путь). Проще и надёжнее
 * держать всю платформенную кухню внутри одной функции, чем протаскивать
 * Uri через общий BackupManager (который работает с простыми путями и
 * должен оставаться платформенно-нейтральным).
 */
@Composable
expect fun rememberBackupCreator(paths: BackupPaths, onResult: (Result<Unit>) -> Unit): () -> Unit

@Composable
expect fun rememberBackupRestorer(paths: BackupPaths, onResult: (Result<Unit>) -> Unit): () -> Unit

/**
 * Перезапуск ПРОЦЕССА приложения — нужен сразу после успешного восстановления
 * из резервной копии (см. BackupManager.restoreBackup): файл БД на диске уже
 * подменён, но уже открытое соединение (repository в MainActivity — по
 * жизни как активити, `by lazy`) продолжает как ни в чём не бывало работать
 * со старыми, уже прочитанными данными.
 *
 * На Desktop закрытие окна = завершение JVM, так что там раньше было
 * достаточно попросить пользователя закрыть и открыть Interes заново — он
 * гарантированно перезапускался целиком. На Android же обычное "закрытие"
 * (кнопка "Домой", переключение задач, даже смахивание из списка недавних
 * без активного foreground-сервиса тоже не всегда убивает процесс на
 * некоторых прошивках) НЕ гарантирует уничтожение процесса — Activity
 * остаётся в памяти, и повторное открытие приложения просто разворачивает
 * ту же самую, уже открытую БД-сессию, а не создаёт её заново. Пользователь
 * честно делает то, что написано в сообщении, но перезапуска не происходит
 * — отсюда ощущение "андроид-версия не восстанавливает данные".
 *
 * actual для Android поэтому не просто "закрывает" приложение, а
 * принудительно убивает процесс и запускает MainActivity в НОВОМ процессе
 * (см. комментарий там же) — так `by lazy`-репозиторий гарантированно
 * пересоздаётся и открывает уже восстановленный файл БД. actual для Desktop
 * — как и раньше, просто завершает процесс (пользователь одним кликом
 * получает то же самое "закрыть-открыть заново", без ручного поиска
 * иконки/ярлыка).
 */
@Composable
expect fun rememberAppRestarter(): () -> Unit
