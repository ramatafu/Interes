package com.interes.shared.ui

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Управляет прозрачностью и положением САМОГО ОКНА на уровне ОС (не только
 * содержимого внутри Compose) — то, что нужно, чтобы сквозь окно Interes
 * реально было видно рабочий стол (Windows на Desktop, домашний экран на
 * Android) и другие приложения под ним, а не просто затемнялось содержимое
 * внутри непрозрачного окна.
 *
 * Desktop — через java.awt.Window (см. NativeWindowController.desktop.kt).
 * Android — через системную alpha окна Activity поверх translucent-темы
 * (androidApp/.../themes.xml, см. NativeWindowController.android.kt).
 *
 * handlesOpacityNatively — не просто "какая платформа сейчас": даже на
 * Windows примерно нулевая, но всё же существующая вероятность, что видеокарта
 * / графический стек не поддерживает оконную полупрозрачность
 * (GraphicsDevice.isWindowTranslucencySupported). AppRoot.kt читает этот
 * флаг и в таком случае откатывается на старый способ (Compose
 * graphicsLayer.alpha — просто гасит содержимое, без реального сквозного
 * эффекта) вместо того, чтобы ползунок молча ничего не делал. На Android
 * флаг всегда true — там этот откат не нужен.
 */
expect class NativeWindowController {
    val handlesOpacityNatively: Boolean
    fun setOpacityPercent(percent: Int)

    /**
     * true, если у платформы есть своё окно с рамкой, которым имеет смысл
     * управлять кнопками "Свернуть/Развернуть/Закрыть" (WindowControlButtons
     * в TopBarIcons.kt) — на Desktop true (у нас собственное undecorated-окно
     * без системной рамки, эти кнопки — единственный способ им управлять).
     * На Android false: окном управляет сама ОС (системная кнопка "Домой"/
     * жест, панель недавних приложений), свои кнопки поверх были бы
     * чужеродными и ничем реальным не управляли бы — AppRoot.kt их не рисует.
     */
    val showWindowControls: Boolean

    /**
     * true, если кнопки "Домой / Создать доску / Резервная копия / О
     * программе" должны рисоваться в ВЕРХНЕМ тулбаре (на одном уровне со
     * значком приложения и лупой, см. AppRoot.kt — там на главном экране),
     * а НЕ в левом боковом тулбаре (SideToolbar.kt).
     *
     * На Android true — там боковая колонка иконок занимает лишнее место
     * на узком экране телефона, эти 4 кнопки переезжают в верхний тулбар.
     * SideToolbar.kt на Android оставляет только корзину (внизу) и стрелку
     * "предыдущее фото" (по центру, во время просмотра) — они НЕ
     * переезжают, см. соответствующий параметр showPrimaryActions в
     * SideToolbar.
     *
     * На Desktop false — там всё остаётся как было: все 5 кнопок
     * (Домой/+/Резервная копия/О программе/Корзина) в левом боковом
     * тулбаре, вертикально.
     */
    val primaryActionsInTopBar: Boolean

    /**
     * Число колонок в сетке досок на главном экране (BoardsListScreen.kt),
     * если оно должно быть ФИКСИРОВАННЫМ, а не подбираться под ширину окна.
     *
     * На Android — 2 (ровно по 2 доски в ряд, независимо от ширины экрана
     * или ориентации). На Desktop — null: там сетка по-прежнему сама
     * подбирает число колонок под ширину окна (AdaptiveMaxColumns, до 8 в
     * ряд на широком окне) — поведение не меняется.
     */
    val fixedBoardGridColumns: Int?

    /**
     * Ширина боковых колонок (SideToolbar.kt / RightToolbar.kt) и связанных
     * с ней элементов верхнего тулбара (значок приложения, декоративные
     * заполнители углов на экране доски/корзины) — ИМЕННО ЭТИМ значением, а
     * не константами ToolbarWidth/RightToolbarWidth напрямую, теперь
     * пользуется AppRoot.kt везде, где раньше был захардкожен 72.dp.
     *
     * На Desktop — 72.dp (ToolbarWidth/RightToolbarWidth без изменений: там
     * в колонках по 4 полноразмерных кнопки, места впритык и так).
     *
     * На Android — 56.dp: на главном экране в этих колонках теперь только
     * "Корзина" и "О программе" внизу (см. showPrimaryActions/showAbout
     * Button), остальное место раньше просто пустовало. Сузив колонки,
     * отдаём эти 2×16.dp = 32.dp сетке досок (BoardsListScreen.kt) — так
     * карточки получаются шире БЕЗ наложения друг на друга (в отличие от
     * прежней попытки принудительно раздвинуть карточку через requiredWidth
     * шире, чем место, реально выделенное сеткой, — то приводило именно к
     * наложению). Кнопки "Корзина"/"О программе" при этом сжаты до 40.dp
     * (TopBarGlyph), а не 64.dp (ToolbarIconButton) — иначе 64.dp кнопка не
     * поместилась бы в 56.dp колонку (см. compact в SideToolbar/RightToolbar).
     */
    val sideToolbarWidth: Dp

    /**
     * Позиция левого верхнего угла окна в экранных координатах — нужна
     * перетаскиванию окна (windowDragHandle) для абсолютного расчёта
     * смещения: окно должно следовать за мышью 1:1, без "вибрации",
     * которую давал старый инкрементальный алгоритм (moveWindowBy).
     * На Android 0 to 0 — там нет отдельного плавающего окна.
     */
    fun getWindowPosition(): Pair<Int, Int>

    /** Ставит окно левым верхним углом в (x, y) экранных координат.
     * На Android пустая реализация. */
    fun setWindowPosition(x: Int, y: Int)

    /**
     * Сдвигает окно на (dxPx, dyPx) пикселей — оставлено для совместимости,
     * перетаскивание теперь идёт через getWindowPosition/setWindowPosition.
     * На Android пустая реализация — там нет отдельного плавающего окна.
     */
    fun moveWindowBy(dxPx: Float, dyPx: Float)

    /** Разворачивает окно на весь экран / возвращает обратно. На Android
     * пустая реализация — там своя модель полноэкранности через Activity. */
    fun toggleMaximize()

    /** Сворачивает окно в панель задач — замена системной кнопки
     * "свернуть", которой больше нет. На Android пустая реализация. */
    fun minimize()

    /**
     * Показывает (и обновляет) сам ползунок прозрачности.
     *
     * Зачем это вообще нужно в контроллере ОКНА, а не просто рисоваться
     * Compose-элементом внутри PhotoViewerControls: на Android
     * setOpacityPercent() гасит альфой ВЕСЬ системный Surface окна Activity
     * целиком — а значит АБСОЛЮТНО ВСЁ, что нарисовано этим же
     * Compose-деревом (включая сам ползунок), гасло бы вместе с фото. Чтобы
     * ползунок оставался полностью читаемым и рабочим при любом проценте
     * прозрачности, на Android он рисуется в ОТДЕЛЬНОМ системном окне
     * (Dialog поверх Activity, см. NativeWindowController.android.kt) —
     * своя alpha, не связанная с alpha главного окна.
     *
     * На Desktop это не нужно: там прозрачность и так не системная
     * (handlesOpacityNatively == false), ползунок как жил в RightToolbar.kt
     * вне затухающего слоя, так и остаётся — здесь пустая реализация.
     *
     * percent — текущее значение (0..100), onChange — вызывается при
     * перетаскивании ползунка пользователем.
     */
    fun showOpacitySlider(percent: Int, onChange: (Int) -> Unit)

    /** Убирает ползунок прозрачности (см. showOpacitySlider). Вызывается
     * при закрытии просмотрщика фото. На Desktop пустая реализация. */
    fun hideOpacitySlider()
}